const { chromium } = require('playwright');
const BASE = 'http://localhost:5173'
;(async () => {
  const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1500, height: 950 }, acceptDownloads: true }); const p = await ctx.newPage()
  const erros = []; p.on('pageerror', (e) => erros.push(e.message)); p.on('console', (m) => m.type() === 'error' && erros.push(m.text()))
  await p.goto(BASE + '/login'); await p.fill('input[type=email]', 'hugo@promovida.pt'); await p.fill('input[type=password]', 'demo1234')
  await p.click('button[type=submit]'); await p.waitForURL(BASE + '/')
  await p.goto(BASE + '/contratos'); await p.getByText('CT-REP-2026/0001').first().click(); await p.waitForURL(/contratos\/\d+/)
  // 1) afetar a loja por atribuir → pergunta pela credencial → nova
  await p.getByRole('button', { name: /Por atribuir/ }).first().click(); await p.getByRole('dialog').waitFor()
  await p.getByRole('combobox').fill('inês'); await p.locator('[role=option]').first().click()
  await p.getByRole('dialog').getByRole('button', { name: 'Guardar' }).click()
  await p.getByText('Emitir credencial para a loja?').waitFor()
  console.log('pergunta:', (await p.getByRole('dialog').innerText()).replace(/\s+/g, ' ').slice(0, 260))
  await p.screenshot({ path: '/tmp/shots/cred-pergunta.png' })
  const [d1] = await Promise.all([p.waitForEvent('download'), p.getByRole('button', { name: 'Emitir credencial nova' }).click()])
  console.log('download 1:', d1.suggestedFilename()); await d1.saveAs('/tmp/cred/e2e1.docx')
  await p.waitForTimeout(500)
  // 2) passar a mesma loja para outro colaborador → por substituição (pré-selecionada)
  await p.locator('tr:has-text("Continente Colombo")').getByRole('button', { name: /Inês Carvalho/ }).click(); await p.getByRole('dialog').waitFor()
  await p.getByRole('button', { name: 'Alterar' }).click(); await p.getByRole('combobox').fill('marco'); await p.locator('[role=option]').first().click()
  await p.getByRole('dialog').getByRole('button', { name: 'Guardar' }).click()
  await p.getByText('Emitir credencial para a loja?').waitFor(); await p.waitForTimeout(400)
  console.log('modo pré-selecionado:', await p.getByRole('radio', { name: /Por substituição/ }).isChecked(), '| a substituir:', await p.getByLabel('Credencial a substituir').locator('option:checked').innerText())
  await p.screenshot({ path: '/tmp/shots/cred-substituicao.png' })
  const [d2] = await Promise.all([p.waitForEvent('download'), p.getByRole('button', { name: 'Emitir por substituição' }).click()])
  console.log('download 2:', d2.suggestedFilename()); await d2.saveAs('/tmp/cred/e2e2.docx')
  // 3) lista de credenciais
  await p.goto(BASE + '/documentacao'); await p.getByRole('button', { name: 'Credenciais', exact: true }).click(); await p.waitForTimeout(600)
  await p.getByLabel('Estado').selectOption(''); await p.waitForTimeout(300)
  console.log('credenciais:', (await p.locator('table.tbl tbody tr').allInnerTexts()).map((t) => t.replace(/\s+/g, ' ').replace(/ Word.*$/, '')).join(' | '))
  await p.screenshot({ path: '/tmp/shots/cred-lista.png' })
  // 4) modelos: nova versão com o ficheiro original
  await p.getByRole('button', { name: 'Modelos de credencial' }).click(); await p.getByRole('button', { name: 'Nova versão' }).click()
  await p.setInputFiles('input[type=file]', '/mnt/user-data/uploads/b07d208b-credencial.docx'); await p.getByLabel('O que mudou (opcional)').fill('Modelo original do cliente')
  await p.getByRole('dialog').getByRole('button', { name: 'Guardar' }).click(); await p.waitForSelector('text=versão 2 guardada')
  await p.getByRole('button', { name: '2 versões' }).click(); await p.waitForTimeout(300)
  console.log('modelos:', (await p.locator('table.tbl tbody tr').allInnerTexts()).map((t) => t.replace(/\s+/g, ' ').replace(/ Descarregar.*$/, '')).join(' | '))
  await p.screenshot({ path: '/tmp/shots/cred-modelos.png' })
  // 5) ficha do colaborador
  await p.goto(BASE + '/colaboradores'); await p.getByRole('link', { name: 'Marco Dias' }).click().catch(async () => { await p.getByText('Marco Dias').first().click() })
  await p.waitForTimeout(800)
  console.log('ficha:', (await p.locator('div.border-t:has(button[aria-expanded]:has-text("Credenciais"))').innerText()).replace(/\s+/g, ' '))
  // 6) parâmetros
  await p.goto(BASE + '/login'); await p.evaluate(() => localStorage.clear())
  await p.goto(BASE + '/login'); await p.fill('input[type=email]', 'marta@promovida.pt'); await p.fill('input[type=password]', 'demo1234'); await p.click('button[type=submit]'); await p.waitForURL(BASE + '/')
  await p.goto(BASE + '/configuracao'); await p.getByRole('button', { name: 'Parâmetros' }).click(); await p.waitForSelector('text=Dados que aparecem nas credenciais')
  await p.screenshot({ path: '/tmp/shots/cred-empresa.png' })
  console.log(erros.length ? 'ERROS ' + erros.join('\n') : 'sem erros'); await b.close()
})()
