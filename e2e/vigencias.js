const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1600, height: 1000 } })
  const erros = []; p.on('pageerror', (e) => erros.push(e.message)); p.on('console', (m) => m.type() === 'error' && !/422/.test(m.text()) && erros.push(m.text()))
  await p.goto('http://localhost:5173/login')
  await p.fill('input[type=email]', 'hugo@promovida.pt'); await p.fill('input[type=password]', 'demo1234'); await p.click('button[type=submit]')
  await p.waitForURL('http://localhost:5173/'); await p.goto('http://localhost:5173/contratos')
  await p.getByText('CT-REP-2026/0001').first().click(); await p.waitForURL(/contratos\/\d+/); await p.getByRole('button', { name: 'Adicionar loja' }).waitFor()
  const n = () => p.locator('table.tbl tbody tr').count()
  console.log('linhas (sem terminadas):', await n(), '| tem Telheiras:', await p.locator('tr:has-text("Pingo Doce Telheiras")').count())
  await p.getByLabel(/Mostrar terminadas/).check()
  console.log('linhas (com terminadas):', await n(), '| badge:', await p.locator('tr:has-text("Pingo Doce Telheiras")').getByText('Terminada').count())
  console.log('fundo:', await p.locator('tr:has-text("Pingo Doce Telheiras") td').first().evaluate((td) => getComputedStyle(td).backgroundColor))
  await p.screenshot({ path: '/tmp/shots/linhas-terminadas.png' })
  // calendário em português e vigência
  await p.getByRole('button', { name: 'Adicionar loja' }).click(); await p.getByRole('dialog').first().waitFor()
  await p.getByRole('dialog').first().getByRole('button', { name: 'Abrir calendário' }).first().click()
  console.log('calendário:', (await p.locator('[aria-label="Calendário"]').innerText()).replace(/\s+/g, ' ').slice(0, 60))
  await p.screenshot({ path: '/tmp/shots/calendario-pt.png' })
  await p.keyboard.press('Escape')
  await p.getByLabel('Início', { exact: true }).fill('15/12/2025'); await p.getByLabel('Início', { exact: true }).press('Tab')
  console.log('erro início:', await p.locator('text=/antes do início do contrato/').innerText())
  console.log('guardar desativado:', await p.getByRole('dialog').first().getByRole('button', { name: 'Guardar' }).isDisabled())
  await p.screenshot({ path: '/tmp/shots/vigencia-erro.png' })
  await p.goto('http://localhost:5173/apuramentos'); await p.waitForTimeout(800)
  await p.getByRole('button', { name: /outubro|novembro/i }).first().click()
  console.log('seletor mês:', (await p.locator('[aria-label="Escolher mês"]').innerText()).replace(/\s+/g, ' '))
  console.log(erros.length ? 'ERROS ' + erros.join('\n') : 'sem erros'); await b.close()
})()
