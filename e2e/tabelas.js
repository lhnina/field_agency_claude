// E2E: CRUD de insígnias e zonas em Clientes e lojas (criar, renomear, desativar, reativar).
const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch()
  const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
  const errors = []
  p.on('pageerror', (e) => errors.push(e.message))
  await p.goto('http://localhost:5173/login')
  await p.fill('input[type=email]', 'hugo@promovida.pt')
  await p.fill('input[type=password]', 'demo1234')
  await p.click('button[type=submit]')
  await p.waitForURL('http://localhost:5173/')
  await p.goto('http://localhost:5173/clientes')
  const segunda = await p.locator('table tbody tr').first().locator('td').first().innerText()
  console.log('linha do cliente:', segunda.replace(/\n/g, ' | '))
  for (const [tab, nome, novo] of [['Insígnias', 'Mercadona', 'Mercadona Portugal'], ['Zonas', 'Setúbal', 'Setúbal e Palmela']]) {
    await p.click(`role=group[name="Secção"] >> button:has-text("${tab}")`)
    await p.fill('input[placeholder="Nome"]', nome)
    await p.click('button:has-text("Acrescentar")')
    await p.waitForSelector(`li:has-text("${nome}")`)
    await p.locator(`li:has-text("${nome}")`).locator('button:has-text("Renomear")').click()
    await p.fill('input[aria-label="Novo nome"]', novo)
    await p.click('li >> button:has-text("Guardar")')
    await p.waitForSelector(`li:has-text("${novo}")`)
    await p.locator(`li:has-text("${novo}")`).locator('button:has-text("Desativar")').click()
    await p.click('role=dialog >> button:has-text("Desativar")')
    await p.waitForSelector(`li:has-text("${novo}")`, { state: 'detached' })
    await p.check('text=Mostrar inativos')
    await p.locator(`li:has-text("${novo}")`).locator('button:has-text("Reativar")').click()
    await p.waitForSelector(`li:has-text("${novo}") >> button:has-text("Desativar")`)
    console.log(`${tab}: criar, renomear, desativar e reativar ok`)
  }
  console.log(errors.length ? 'ERROS: ' + errors.join('\n') : 'sem erros')
  await b.close()
  if (errors.length) process.exit(1)
})().catch((e) => { console.error(e); process.exit(1) })
