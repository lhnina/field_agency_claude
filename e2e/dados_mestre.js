// E2E: clientes e lojas em lista + cartão, edição, desativação (bloqueada com contratos) e logótipo.
const { chromium } = require('playwright')
const out = process.argv[2] || '/tmp/shots'
;(async () => {
  const b = await chromium.launch()
  const p = await b.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  p.on('pageerror', (e) => errors.push(e.message))
  p.on('console', (m) => { if (m.type() === 'error' && !m.text().includes('422')) errors.push(m.text()) })
  await p.goto('http://localhost:5173/login')
  console.log('logo no login:', await p.locator('img[alt="Argos"]').isVisible())
  await p.fill('input[type=email]', 'hugo@promovida.pt')
  await p.fill('input[type=password]', 'demo1234')
  await p.click('button[type=submit]')
  await p.waitForURL('http://localhost:5173/')
  console.log('título:', await p.title(), '| marca na barra:', (await p.locator('nav').innerText()).includes('ARGOS'))

  await p.goto('http://localhost:5173/clientes')
  await p.waitForSelector('text=Gestor de conta')
  await p.click('table >> button:has-text("Atlântico Conservas")')
  await p.click('button:has-text("Editar")')
  await p.getByLabel('Telefone').fill('213 456 789')
  await p.getByLabel('Site').fill('atlantico.pt')
  await p.getByLabel('Gestor de conta').fill('Marta Ribeiro')
  await p.click('role=dialog >> button:has-text("Guardar")')
  await p.waitForSelector('text=Cliente atualizado')
  await p.waitForTimeout(400)
  const cartao = await p.locator('section').nth(1).innerText()
  console.log('cartão atualizado:', cartao.includes('213 456 789') && cartao.includes('Marta Ribeiro'))
  await p.screenshot({ path: `${out}/dm-clientes.png`, fullPage: true })
  // desativar cliente com contratos ativos: bloqueado com mensagem
  await p.locator('section').nth(1).locator('button:has-text("Desativar")').last().click()
  await p.click('role=dialog >> button:has-text("Desativar")')
  await p.waitForSelector('role=dialog >> text=/termine-os antes/')
  console.log('bloqueio: true')
  await p.click('role=dialog >> button:has-text("Cancelar")')

  await p.click('role=group[name="Secção"] >> button:has-text("Lojas")')
  await p.waitForSelector('text=Serviços em vigor')
  await p.click('table >> button:has-text("Lidl Odivelas")')
  await p.waitForTimeout(300)
  await p.screenshot({ path: `${out}/dm-lojas.png`, fullPage: true })
  console.log(errors.length ? 'ERROS: ' + errors.join('\n') : 'sem erros')
  await b.close()
  if (errors.length) process.exit(1)
})().catch((e) => { console.error(e); process.exit(1) })
