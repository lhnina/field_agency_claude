const { chromium } = require('playwright');
const BASE = 'http://localhost:5173'
;(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1500, height: 950 } })
  const erros = []; p.on('pageerror', (e) => erros.push(e.message)); p.on('console', (m) => m.type() === 'error' && erros.push(m.text()))
  await p.goto(BASE + '/login'); await p.fill('input[type=email]', 'hugo@promovida.pt'); await p.fill('input[type=password]', 'demo1234')
  await p.click('button[type=submit]'); await p.waitForURL(BASE + '/')
  await p.goto(BASE + '/clientes'); await p.waitForSelector('table.tbl tbody tr')
  await p.getByRole('button', { name: 'Atlântico Conservas' }).click(); await p.waitForTimeout(400)
  console.log('cartão sem marcas:', !(await p.locator('text="Marcas"').count()))
  await p.getByRole('button', { name: 'Editar' }).first().click(); await p.getByRole('dialog').waitFor()
  const chips = async () => (await p.locator('[aria-label="Marcas do cliente"] > span').allInnerTexts()).map((t) => t.trim())
  console.log('marcas existentes:', (await chips()).join(', '))
  await p.getByPlaceholder('Nova marca').fill('Mar Azul Gourmet'); await p.getByPlaceholder('Nova marca').press('Enter')
  await p.getByRole('button', { name: 'Retirar a marca Mar Azul', exact: true }).click()
  console.log('depois:', (await chips()).join(', '))
  await p.screenshot({ path: '/tmp/shots/marcas.png' })
  await p.getByRole('dialog').getByRole('button', { name: 'Guardar' }).click(); await p.waitForSelector('text=Cliente atualizado')
  const r = await p.evaluate(async () => (await (await fetch('/api/clientes', { headers: { Authorization: 'Bearer ' + localStorage.getItem('fa.token') } })).json()).find((c) => c.nome === 'Atlântico Conservas').marcas)
  console.log('gravado:', r.map((m) => `${m.nome}${m.ativo ? '' : ' (inativa)'}`).join(', '))
  // insígnias: logótipo
  await p.goto(BASE + '/clientes'); await p.getByRole('button', { name: 'Insígnias' }).click(); await p.waitForSelector('text=Continente')
  await p.setInputFiles('input[aria-label="Logótipo de Continente"]', '/tmp/logo-teste.png'); await p.waitForSelector('text=Logótipo guardado')
  await p.waitForTimeout(400); await p.screenshot({ path: '/tmp/shots/insignias-logo.png' })
  await p.getByRole('button', { name: 'Lojas', exact: true }).click(); await p.waitForSelector('table.tbl tbody tr'); await p.waitForTimeout(600)
  console.log('miniaturas nas lojas:', await p.locator('table.tbl tbody img').count(), '| ERP:', (await p.locator('table.tbl tbody tr').first().innerText()).replace(/\s+/g, ' '))
  await p.screenshot({ path: '/tmp/shots/lojas-logo.png' })
  console.log(erros.length ? 'ERROS ' + erros.join('\n') : 'sem erros'); await b.close()
})()
